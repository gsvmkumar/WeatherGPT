export function useTranslation(lang: string) {
  const code = (lang as SupportedLanguage) in TRANSLATIONS ? (lang as SupportedLanguage) : 'en';
  const selectedTranslations = TRANSLATIONS[code];
  const englishFallback = TRANSLATIONS.en;

  // Proxy to safely fallback to English for any un-translated key
  const t = new Proxy(selectedTranslations, {
    get(target, prop: string) {
      if (prop in target) {
        return target[prop];
      }
      return englishFallback[prop] ?? '';
    },
  });

  return {
    t,
    lang: code,
    isTelugu: code === 'te',
  };
}
